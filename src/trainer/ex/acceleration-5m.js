// Ускорение 5 метров: показаны старт и первые четыре шага (путь 1,4 м), остановка и спокойный возврат шагами назад.
// Старт из разножки: левая впереди, правая сзади, корпус наклонён вперёд на 40°. Первый шаг правой с толчка подушечкой,
// шаги короткие и частые, корпус выпрямляется постепенно (к четвёртому шагу около 60°), руки работают от плеча.
// Торможение: последний шаг шире, таз вниз и назад, корпус прямой. Ракурс спереди-сбоку: видно наклон и шаги.
import { script, measureFeet, gait, legAudit } from '../steps.js';

const C = 5.6; // = сумма tempo_s фаз: цикл показа берётся из фаз

export function build(T) {
  const { rig } = T, L = rig.L1 + rig.L2, A = rig.ankleH, y = (k) => A + k * L;
  const S = script(C, { Left: { x: 0.11, z: 0, yaw: 0.05 }, Right: { x: -0.11, z: -0.3, yaw: -0.05 } });
  // разгон: толчок с подушечки (push), шаги растут 0,5 → 0,6 → 0,65 м, между ними короткий полёт
  S.step('Right', 0.3, 0.6, -0.11, 0.5, -0.03, { push: 0.4 }); // push — пятка встаёт к отрыву: бег с передней части стопы
  S.step('Left', 0.54, 0.84, 0.11, 1.1, 0.03, { push: 0.4 });
  S.step('Right', 0.74, 1.06, -0.11, 1.75, -0.03, { push: 0.4 });
  S.step('Left', 1.0, 1.28, 0.15, 2.05, 0.1, { h: 0.08 }); // тормозящий шаг: короче и шире
  S.step('Right', 1.42, 1.7, -0.15, 2.0, -0.1, { h: 0.05 }); // приставить: стойка
  // возврат спиной вперёд: шесть спокойных шагов
  S.step('Left', 2.9, 3.25, 0.11, 1.65, 0.05, { h: 0.05 });
  S.step('Right', 3.3, 3.65, -0.11, 1.25, -0.05, { h: 0.05 });
  S.step('Left', 3.7, 4.05, 0.11, 0.85, 0.05, { h: 0.05 });
  S.step('Right', 4.1, 4.45, -0.11, 0.45, -0.05, { h: 0.05 });
  S.step('Left', 4.5, 4.85, 0.11, 0, 0.05, { h: 0.05 });
  S.step('Right', 4.9, 5.25, -0.11, -0.3, -0.05, { h: 0.05 });
  for (const p of S.plants.Right) if (Math.abs(p.on) < 1e-9) p.push = 0.4; // старт толчком задней ноги
  // gait — нога в махе и таз по клипу бега, run — руки клипа, v — скорость для клипа (разгон ~4,5 м/с)
  const k = (t, o) => S.key(t, { y: y(0.86), dx: 0, dz: 0.05, yaw: 0, hips: 0, torso: 0, elev: 50, run: 0, gait: 0, hang: 0, v: 4, ...o });
  k(0, { y: y(0.86), dz: 0.06, elev: 50 });
  k(0.25, { y: y(0.88), dz: 0.12, elev: 48, run: 1, gait: 0.6 });
  k(0.6, { y: y(0.93), dz: 0.06, elev: 56, run: 1, gait: 1 });
  k(1.0, { y: y(0.92), dz: 0.06, elev: 66, run: 1, gait: 1 });
  k(1.3, { y: y(0.86), dz: -0.06, elev: 74, run: 0.3, gait: 0.2 });
  k(1.9, { y: y(0.87), dz: -0.03, elev: 78, run: 0, gait: 0 });
  k(2.6, { y: y(0.95), dz: 0, elev: 89, run: 0, hang: 0.6 });
  k(5.2, { y: y(0.95), dz: 0, elev: 88, run: 0, hang: 0.4 });
  return S.done();
}

export default {
  id: 'acceleration-5m',
  name: 'Ускорение 5 метров',
  muscles: { work: ['glutes', 'quads', 'calves', 'hamstrings'], stretch: [], careful: ['hamstrings', 'ankle'] },
  phases: [
    { name: 'старт', cue: 'Наклон вперёд, мощный толчок', tempo_s: 0.6 },
    { name: 'разгон', cue: 'Короткие частые шаги', tempo_s: 0.5 },
    { name: 'торможение', cue: 'Мягко остановись', tempo_s: 1.4 },
    { name: 'возврат', cue: 'Шагом назад на старт', tempo_s: 3.1 }, // сумма фаз = цикл сценария C
  ],
  mistakes: ['Выпрямление на первом шаге', 'Старт без разминки'],
  dose: { sets: '6', reps: '1 × 5 м', rest_s: 45 },
  view: 'quarter',
  flat: 'side',
  wide: true,
  pace: 'В жизни старт в полную силу, 5 м',
  setup(T) { measureFeet(T); T.S = build(T); },
  pose(T, { t }) { T.tNow = t; gait(T, T.S, t); },
  audit(T) {
    const r = legAudit(T), tau = ((T.tNow % C) + C) % C;
    // Главное в старте: корпус наклонён на первых шагах (не выпрямиться сразу).
    if (tau < 0.75 && r.m.torso > 62) r.bad.push(`корпус выпрямлен на первом шаге: ${r.m.torso}°`);
    return r;
  },
};
