// Ускорение 5 метров: показаны старт и первые четыре шага (путь 1,4 м), остановка и спокойный возврат шагами назад.
// Старт из разножки: левая впереди, правая сзади, корпус наклонён вперёд на 40°. Первый шаг правой с толчка подушечкой,
// шаги короткие и частые, корпус выпрямляется постепенно (к четвёртому шагу около 60°), руки работают от плеча.
// Торможение: последний шаг шире, таз вниз и назад, корпус прямой. Ракурс спереди-сбоку: видно наклон и шаги.
import { script, measureFeet, gait, legAudit } from '../steps.js';

const C = 5.2;

export function build(T) {
  const { rig } = T, L = rig.L1 + rig.L2, A = rig.ankleH, y = (k) => A + k * L;
  const S = script(C, { Left: { x: 0.12, z: 0.1, yaw: 0.05 }, Right: { x: -0.12, z: -0.25, yaw: -0.05 } });
  // разгон: толчок с подушечки (push), шаги вперёд
  S.step('Right', 0.3, 0.58, -0.11, 0.32, -0.03, { h: 0.1 });
  S.step('Left', 0.58, 0.84, 0.11, 0.72, 0.03, { h: 0.11 });
  S.step('Right', 0.76, 1.04, -0.11, 1.1, -0.03, { h: 0.11 });
  S.step('Left', 1.0, 1.3, 0.15, 1.38, 0.1, { h: 0.08 }); // тормозящий шаг: шире
  S.step('Right', 1.42, 1.7, -0.15, 1.33, -0.1, { h: 0.05 }); // приставить: стойка
  // возврат спиной вперёд: шесть спокойных шагов
  S.step('Left', 2.9, 3.2, 0.12, 1.0, 0.05, { h: 0.05 });
  S.step('Right', 3.25, 3.55, -0.12, 0.8, -0.05, { h: 0.05 });
  S.step('Left', 3.6, 3.9, 0.12, 0.5, 0.05, { h: 0.05 });
  S.step('Right', 3.95, 4.25, -0.12, 0.3, -0.05, { h: 0.05 });
  S.step('Left', 4.3, 4.6, 0.12, 0.1, 0.05, { h: 0.05 });
  S.step('Right', 4.65, 4.95, -0.12, -0.25, -0.05, { h: 0.05 });
  for (const p of S.plants.Right) if (Math.abs(p.on) < 1e-9) p.push = 0.5; // старт толчком задней ноги
  const k = (t, o) => S.key(t, { y: y(0.86), dx: 0, dz: 0.05, yaw: 0, hips: 0, torso: 0, elev: 50, run: 0, ...o });
  k(0, { y: y(0.86), dz: 0.06, elev: 50 });
  k(0.25, { y: y(0.85), dz: 0.12, elev: 46, run: 0.6 });
  k(0.6, { y: y(0.88), dz: 0.14, elev: 50, run: 1 });
  k(1.05, { y: y(0.9), dz: 0.1, elev: 60, run: 1 });
  k(1.4, { y: y(0.84), dz: -0.06, elev: 72, run: 0.3 });
  k(1.9, { y: y(0.85), dz: -0.03, elev: 76, run: 0 });
  k(2.6, { y: y(0.93), dz: 0, elev: 84, run: 0, hang: 0.6 });
  k(4.8, { y: y(0.92), dz: 0, elev: 82, run: 0, hang: 0.4 });
  S.stride = 0.5;
  return S.done();
}

export default {
  id: 'acceleration-5m',
  name: 'Ускорение 5 метров',
  muscles: { work: ['glutes', 'quads', 'calves', 'hamstrings'], stretch: [], careful: ['hamstrings', 'ankle'] },
  phases: [
    { name: 'старт', cue: 'Наклон вперёд, мощный толчок', tempo_s: 0.85 },
    { name: 'разгон', cue: 'Короткие частые шаги', tempo_s: 0.55 },
    { name: 'торможение', cue: 'Мягко остановись', tempo_s: 1.5 },
    { name: 'возврат', cue: 'Шагом назад на старт', tempo_s: 2.3 },
  ],
  mistakes: ['Выпрямление на первом шаге', 'Старт без разминки'],
  dose: { sets: '6', reps: '1 × 5 м', rest_s: 45 },
  view: 'quarter',
  flat: 'side',
  wide: true,
  pace: 'В жизни старт в полную силу, 5 м',
  setup(T) { measureFeet(T); T.S = build(T); },
  pose(T, { t }) { T.tNow = t; gait(T, T.S, t); },
  audit(T) {
    const r = legAudit(T), tau = ((T.tNow % C) + C) % C;
    // Главное в старте: корпус наклонён на первых шагах (не выпрямиться сразу).
    if (tau < 0.9 && r.m.torso > 62) r.bad.push(`корпус выпрямлен на первом шаге: ${r.m.torso}°`);
    return r;
  },
};
